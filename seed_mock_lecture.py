# ------------------------------------------------------------------ Running code
def run(code, stdin):
    """(stdout, stderr, returncode or None on timeout)"""
    try:
        p = subprocess.run([sys.executable, "-c", code], input=stdin, capture_output=True,
                           text=True, timeout=TIMEOUT_S)
        return p.stdout, p.stderr, p.returncode
    except subprocess.TimeoutExpired:
        return "", "", None


def check_programs():
    """Stops the script if any program doesn't behave as its label says."""
    problems = []
    for task in TASKS:
        tests = task["tests"]
        expected = [o for _, o in tests]
        ref_out = [run(task["reference"], i)[0].strip() for i, _ in tests]
        if ref_out != expected:
            problems.append(f"{task['title']}: reference gives {ref_out}")
        for code in task["correct"]:
            if [run(code, i)[0].strip() for i, _ in tests] != expected:
                problems.append(f"{task['title']}: a correct variant fails")
        codes = [c for _, _, c in task["wrong"]]
        if len(codes) != len(set(codes)) or set(codes) & set(task["correct"]):
            problems.append(f"{task['title']}: wrong programs aren't all unique")
        signatures = {}
        for bug, kind, code in task["wrong"]:
            results = [run(code, i) for i, _ in tests]
            outs = [r[0].strip() for r in results]
            errs = " ".join(r[1] for r in results)
            if kind == "wrong":
                if any(r[2] != 0 for r in results) or outs == expected:
                    problems.append(f"{task['title']}/{bug}: should run and be wrong")
                signatures.setdefault(bug, set()).add(tuple(outs))
            elif kind == "timeout":
                if not any(r[2] is None for r in results):
                    problems.append(f"{task['title']}/{bug}: never times out")
            elif kind in ("syntax", "unfinished"):
                if kind == "syntax" and "SyntaxError" not in errs:
                    problems.append(f"{task['title']}/{bug}: compiles")
                if kind == "unfinished" and outs == expected:
                    problems.append(f"{task['title']}/unfinished: passes")
            else:  # exception name
                if f"{kind}:" not in errs:
                    problems.append(f"{task['title']}/{bug}: doesn't raise {kind}")
        for bug, sigs in signatures.items():
            if len(sigs) != 1:
                problems.append(f"{task['title']}/{bug}: variants print different things")
    if problems:
        sys.exit("Program check failed:\n  " + "\n  ".join(problems))
    n = sum(len(t["wrong"]) for t in TASKS)
    print(f"Program check OK: {len(TASKS)} tasks, {n} unique wrong/unfinished programs, all behave as labeled.")


# ------------------------------------------------------------------ Judge0 stand-in
def _b64(s):
    return base64.b64encode((s or "").encode()).decode()


def fake_post(url, params=None, json=None, headers=None, timeout=None):
    if not url.endswith("/submissions"):
        raise ConnectionError("seed script: no network calls besides the Judge0 stand-in")
    stdout, stderr, code = run(base64.b64decode(json["source_code"]).decode(),
                               base64.b64decode(json.get("stdin") or "").decode())
    if code is None:
        status = {"id": 5, "description": "Time Limit Exceeded"}
    elif code == 0:
        status = {"id": 3, "description": "Accepted"}
    else:
        status = {"id": 11, "description": "Runtime Error (NZEC)"}
    resp = MagicMock()
    resp.raise_for_status = lambda: None
    resp.json.return_value = {
        "status": status, "stdout": _b64(stdout), "stderr": _b64(stderr) if stderr else None,
        "compile_output": None, "message": None, "time": "0.02", "memory": 3500, "exit_code": code,
    }
    return resp


# ------------------------------------------------------------------ Who submits what
def plan_task(rng, task, students):
    """{student: [code, ...]} in submission order. Every wrong program goes to exactly one
    student; no student gets two programs with the same bug, so each bug's variants come
    from different students. Unfinished code is always a student's last submission and
    they never solve. A couple of students submit nothing."""
    finished = [w for w in task["wrong"] if w[1] != "unfinished"]
    unfinished = [w for w in task["wrong"] if w[1] == "unfinished"]
    rng.shuffle(finished)
    order = students[:]
    rng.shuffle(order)
    plan = {s: [] for s in order}
    bugs = {s: set() for s in order}

    out_of_time = order[:len(unfinished)]
    n_struggling = max(1, round(len(finished) * 0.65))
    struggling = order[len(unfinished):len(unfinished) + n_struggling]
    rest = order[len(unfinished) + n_struggling:]
    silent = rest[:rng.choice([1, 2])]
    first_try = rest[len(silent):]

    receivers = struggling + out_of_time[: len(out_of_time) // 2]  # some ran out after a wrong try
    i = 0
    for bug, _kind, code in finished:
        for _ in range(len(receivers)):
            s = receivers[i % len(receivers)]
            i += 1
            if bug not in bugs[s] and len(plan[s]) < 3:
                plan[s].append(code)
                bugs[s].add(bug)
                break
        else:
            raise RuntimeError(f"couldn't place a {bug} program")
    for s, (_bug, _kind, code) in zip(out_of_time, unfinished):
        plan[s].append(code)
    for s in struggling:
        if rng.random() < 0.6:
            plan[s].append(rng.choice(task["correct"]))
    for s in first_try:
        plan[s].append(rng.choice(task["correct"]))
    for s in silent:
        plan[s] = []
    return plan


# ------------------------------------------------------------------ Main
def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--db", default=str(REPO / "backend" / "prototype.db"))
    ap.add_argument("--finish-active", action="store_true", help="finish a running lecture first")
    ap.add_argument("--check", action="store_true", help="only verify the programs, touch nothing")
    args = ap.parse_args()

    check_programs()
    if args.check:
        return

    db = Path(args.db)
    if db.exists():
        backup = db.with_name(f"{db.stem}-backup-{datetime.now():%Y-%m-%d-%H%M%S}.db")
        shutil.copy2(db, backup)
        print(f"Backed up {db.name} -> {backup.name}")

    os.environ["PROTOTYPE_DB_PATH"] = str(db)
    os.environ["LLM_PROVIDER"] = "idun"  # no key: no AI calls from the seed itself
    os.environ["IDUN_API_KEY"] = ""
    sys.path.insert(0, str(REPO))

    with patch("backend.judge0_client.requests.post", side_effect=fake_post):
        from fastapi.testclient import TestClient
        from backend.main import app

        with TestClient(app) as client:
            def ok(r):
                assert r.status_code == 200, (r.request.url, r.status_code, r.text)
                return r.json()

            active = ok(client.get("/api/lecturer/lectures/active"))
            if active["lecture"]:
                if not args.finish_active:
                    sys.exit(f"Lecture #{active['lecture']['id']} ({active['lecture']['display_label']}) "
                             "is active. Finish it first, or rerun with --finish-active.")
                ok(client.post("/api/lecturer/lecture/finish",
                               json={"current_question_id": active["live_question_id"]}))
                print(f"Finished the active lecture #{active['lecture']['id']}")

            rng = random.Random(SEED)
            lecture = ok(client.post("/api/lecturer/lectures", json={"label": LABEL}))
            ok(client.post(f"/api/lecturer/lectures/{lecture['id']}/open_lobby"))
            tokens = {}  # each student's join token -- what their calls send
            for name in STUDENTS:
                joined = ok(client.post("/api/lecture/join", json={"code": lecture["join_code"], "student_name": name}))
                tokens[name] = {"X-Student-Token": joined["token"]}

            qids = []
            for task in TASKS:
                q = ok(client.post("/api/lecturer/questions", json={
                    "title": task["title"], "prompt": task["prompt"], "language": "python",
                    "test_cases": [{"stdin": i, "expected_stdout": o} for i, o in task["tests"]],
                    "reference_solution": task["reference"], "starter_code": task["starter"],
                    "expected_students": len(STUDENTS) + 2, "duration_seconds": 600,
                }))
                v = ok(client.post(f"/api/lecturer/questions/{q['id']}/validate"))
                assert v["validated"], (task["title"], v)
                qids.append(q["id"])

            current = None
            for task, qid in zip(TASKS, qids):
                started = ok(client.post("/api/lecturer/lecture/next", json={"current_question_id": current}))
                assert started["started"]["id"] == qid, started
                current = qid
                plan = plan_task(rng, task, STUDENTS)
                for name, codes in plan.items():
                    if codes or rng.random() < 0.5:  # silent students sometimes opened the editor
                        ok(client.post("/api/lecture/activity",
                                       json={"question_id": qid, "edited": True}, headers=tokens[name]))
                auto = {c for b, k, c in task["wrong"] if k == "unfinished"}

                def submit(name, code):
                    ok(client.post("/api/submit", json={"question_id": qid, "source_code": code},
                                   headers=tokens[name]))

                for round_no in range(4):  # everyone's 1st attempt, then 2nd, ...
                    for name, codes in plan.items():
                        typed = [c for c in codes if c not in auto]
                        if round_no < len(typed):
                            submit(name, typed[round_no])
                for name, codes in plan.items():  # time's up: unfinished code auto-submitted last
                    for c in codes:
                        if c in auto:
                            submit(name, c)
                with sqlite3.connect(db) as conn:
                    verdicts = dict(conn.execute(
                        "SELECT exec_verdict || COALESCE(' ' || NULLIF(error_type, 'none'), ''), COUNT(*) "
                        "FROM submissions WHERE question_id = ? GROUP BY 1", (qid,)).fetchall())
                n_subs = sum(len(c) for c in plan.values())
                silent = sum(1 for c in plan.values() if not c)
                print(f"  {task['title']}: {n_subs} submissions, {silent} silent -- "
                      + ", ".join(f"{k} {v}" for k, v in sorted(verdicts.items())))
            ok(client.post(f"/api/lecturer/questions/{current}/end_now"))

    unfinished = {c for t in TASKS for b, k, c in t["wrong"] if k == "unfinished"}
    backdate(db, lecture["id"], qids, unfinished, random.Random(SEED + 1))
    print(f"\nLecture #{lecture['id']} '{LABEL}' is live on its last task, time up.")
    print("Open the lecturer dashboard; the AI text appears if the backend has IDUN_API_KEY loaded.")


def backdate(db, lecture_id, question_ids, unfinished, rng):
    """Spreads the lecture over the last ~50 minutes (UTC, as the app stores it): tasks
    12 minutes apart, 10 minutes each, submissions spread through each task, so timelines
    and progress views read like a real session. Unfinished code lands at time-up, when the
    student page auto-submits it. The last task's time is up."""
    fmt = "%Y-%m-%d %H:%M:%S"
    now = datetime.utcnow()
    start = now - timedelta(minutes=12 * len(question_ids) + 8)
    conn = sqlite3.connect(db)
    conn.execute("UPDATE lectures SET started_at = ?, lobby_opened_at = ? WHERE id = ?",
                 (start.strftime(fmt), (start + timedelta(minutes=1)).strftime(fmt), lecture_id))
    conn.execute("UPDATE lecture_joins SET joined_at = ? WHERE lecture_id = ?",
                 ((start + timedelta(minutes=2)).strftime(fmt), lecture_id))
    for i, qid in enumerate(question_ids):
        q_start = start + timedelta(minutes=5 + 12 * i)
        conn.execute("UPDATE questions SET started_at = ?, duration_seconds = 600 WHERE id = ?",
                     (q_start.strftime(fmt), qid))
        for sub_id, attempt, code in conn.execute(
            "SELECT id, attempt_number, source_code FROM submissions WHERE question_id = ?", (qid,)
        ).fetchall():
            if code in unfinished:
                t = q_start + timedelta(seconds=600)
            else:
                t = q_start + timedelta(seconds=min(580, 70 + (attempt - 1) * 150 + rng.randint(0, 120)))
            conn.execute("UPDATE submissions SET created_at = ? WHERE id = ?", (t.strftime(fmt), sub_id))
    conn.commit()
    conn.close()


